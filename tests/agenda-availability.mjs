import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const source = ts.transpileModule(fs.readFileSync("lib/agendaAvailability.ts", "utf8"), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const a = await import("data:text/javascript;base64," + Buffer.from(source).toString("base64"));
const professionals = [{id:"ana",active:true,closedShifts:[{weekday:1,shift:"morning"}]},{id:"bia",active:true},{id:"off",active:false}];
const monday = "2026-10-12", saturday = "2026-10-10";
const resizeRecord={startsAt:saturday+'T08:00:00',endsAt:saturday+'T09:00:00'};
assert.equal(a.resizedAgendaEnd(resizeRecord,2),saturday+'T10:00:00');
assert.equal(a.resizedAgendaEnd(resizeRecord,-10),saturday+'T08:30:00');
assert.equal(a.resizedAgendaEnd(resizeRecord,99),saturday+'T21:00:00');
assert.equal(a.resizedAgendaEnd({...resizeRecord,endsAt:saturday+'T08:45:00'},1),saturday+'T09:30:00');
assert.equal(a.resizedAgendaEnd({...resizeRecord,endsAt:'2026-10-11T01:00:00'},1),null);
assert.ok(a.validClosedShifts(professionals[0].closedShifts));
assert.equal(a.validClosedShifts([{weekday:7,shift:"morning"}]),false);
assert.equal(a.validClosedShifts([{weekday:1,shift:"invalid"}]),false);
assert.ok(a.shiftClosed(professionals[0],monday,8));
assert.ok(a.shiftClosed(professionals[0],monday,11.5,12.5));
assert.equal(a.shiftClosed(professionals[0],monday,12),false);
assert.equal(a.shiftClosed(professionals[0],saturday,8),false);
const selection=a.rectangleSlots(saturday,["ana","bia"],{professionalId:"ana",hour:8},{professionalId:"bia",hour:10});
assert.equal(selection.length,10);
assert.deepEqual(a.rectangleSlots(saturday,["ana","bia"],{professionalId:"bia",hour:10},{professionalId:"ana",hour:8}),selection);
assert.deepEqual(a.bookingDuration(selection,"ana"),{hour:8,durationMinutes:150});
assert.equal(a.bookingDuration([selection[0],selection[2]],"ana").durationMinutes,30);
const occupied={id:"patient",professionalId:"ana",startsAt:saturday+"T09:30:00",endsAt:saturday+"T10:30:00",status:"Agendado"};
let count=0;
const absences=a.newAbsences(professionals,[occupied],[...selection,...selection],()=>"absence-"+(++count));
assert.equal(absences.length,8);
assert.equal(absences.every(a.isAbsence),true);
assert.equal(a.overlappingAppointments([occupied],{date:saturday,professionalId:"ana",hour:10}).length,1);
assert.equal(a.newAbsences(professionals,[...absences,occupied],selection,()=>"duplicate").length,0);
assert.match(a.appointmentAvailabilityError(professionals[0],[],monday+"T09:00:00",monday+"T10:00:00"),/fechada/);
assert.match(a.appointmentAvailabilityError(professionals[1],absences,saturday+"T09:30:00",saturday+"T10:30:00"),/ausente/);
assert.equal(a.newAbsences(professionals,[],[{date:monday,professionalId:"ana",hour:8},{date:monday,professionalId:"off",hour:14}],()=>"blocked").length,0);
console.log("PASS: weekly closure boundaries, reverse rectangular selection, contiguous booking duration, overlapping patient protection, idempotent absence selection and booking conflict validation.");

assert.deepEqual(a.reservedInterval("2026-10-10T08:00:00","2026-10-10T09:20:00"), {start:"2026-10-10T08:00:00",end:"2026-10-10T09:30:00"});
assert.deepEqual(a.reservedInterval("2026-10-10T08:30:00","2026-10-10T10:00:00"), {start:"2026-10-10T08:30:00",end:"2026-10-10T10:00:00"});
assert.equal(a.reservedInterval("bad","bad"),null);
const longVisit={id:"long",professionalId:"bia",startsAt:saturday+"T08:00:00",endsAt:saturday+"T09:20:00"};
assert.match(a.appointmentAvailabilityError(professionals[1],[longVisit],saturday+"T09:15:00",saturday+"T09:45:00"),/reservado/);
assert.equal(a.appointmentAvailabilityError(professionals[1],[longVisit],saturday+"T10:00:00",saturday+"T11:00:00"),"");
assert.equal(a.appointmentAvailabilityError(professionals[1],[longVisit],longVisit.startsAt,longVisit.endsAt,"long"),"");
assert.match(a.appointmentAvailabilityError(professionals[0],[],"2026-10-11T20:00:00","2026-10-12T09:00:00"),/fechada/);
console.log("PASS: half-hour reservation rounds the final partial block up, exact endings release the next half-hour, overlap is rejected, own edit is excluded and recurring closure covers following days.");

assert.equal(a.slotTime(8.5),"08:30");assert.equal(a.slotTime(20.5),"20:30");
assert.equal(a.slotAvailable(professionals,[],{date:saturday,professionalId:"bia",hour:20.5}),true);
assert.equal(a.slotAvailable(professionals,[],{date:saturday,professionalId:"bia",hour:21}),false);
assert.deepEqual(a.reservedInterval(saturday+"T08:00:00",saturday+"T08:30:00"),{start:saturday+"T08:00:00",end:saturday+"T08:30:00"});
assert.deepEqual(a.reservedInterval(saturday+"T08:10:00",saturday+"T08:40:00"),{start:saturday+"T08:00:00",end:saturday+"T09:00:00"});
assert.equal(a.appointmentAvailabilityError(professionals[1],[longVisit],saturday+"T09:30:00",saturday+"T10:00:00"),"");
assert.equal(a.overlappingAppointments([occupied],{date:saturday,professionalId:"ana",hour:9}).length,0);
assert.equal(a.overlappingAppointments([occupied],{date:saturday,professionalId:"ana",hour:9.5}).length,1);
assert.match(a.appointmentAvailabilityError({...professionals[1],closedShifts:[{weekday:6,shift:"afternoon"}]},[],saturday+"T12:00:00",saturday+"T12:30:00"),/fechada/);
console.log("PASS: 30-minute adjacency, fractional starts, 20:30 selection, partial-period closure validation and correct half-hour overlap.");
